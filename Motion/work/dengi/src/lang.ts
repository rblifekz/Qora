export const warp = (t: number): number => {
  const a = ANCHORS[LANG.current];
  if (!a.length) return t;
  if (t <= a[0][0]) return t - a[0][0] + a[0][1];
  for (let i = 1; i < a.length; i++) {
    if (t <= a[i][0]) {
      const [x0, y0] = a[i - 1];
      const [x1, y1] = a[i];
      return y0 + ((t - x0) / (x1 - x0)) * (y1 - y0);
    }
  }
  const [xl, yl] = a[a.length - 1];
  return yl + (t - xl);
};
